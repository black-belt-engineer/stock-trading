#!/usr/bin/env bash
# Bootstraps and runs the whole stack locally.
#
#   scripts/dev.sh               # setup + start every app in watch mode
#   scripts/dev.sh --setup-only  # setup, then exit (infra stays up)
#   scripts/dev.sh --down        # stop the docker infrastructure
#   scripts/dev.sh --reset-realm # also delete the Keycloak realm and reimport it from
#                                # infra/keycloak (combine with --setup-only if wanted)
#
# Setup is idempotent: re-running only does what is missing.
# Keycloak imports the realm only when it does not exist yet: after editing the realm JSON
# or regenerating KC_BFF_CLIENT_SECRET, run with --reset-realm.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

ENV_FILE=".env.local"
COMPOSE=(docker compose --env-file "$ENV_FILE")

log()  { printf '\033[1;34m==>\033[0m %s\n' "$*"; }
die()  { printf '\033[1;31merror:\033[0m %s\n' "$*" >&2; exit 1; }

KEYCLOAK_REALM="stock-platform"
REALM_FILE="infra/keycloak/realm-${KEYCLOAK_REALM}.json"

SETUP_ONLY=false
RESET_REALM=false
for arg in "$@"; do
  case "$arg" in
    --setup-only) SETUP_ONLY=true ;;
    --reset-realm) RESET_REALM=true ;;
    --down)
      [[ -f "$ENV_FILE" ]] || ENV_FILE=".env.local.example"
      COMPOSE=(docker compose --env-file "$ENV_FILE")
      log "Stopping infrastructure"
      "${COMPOSE[@]}" down
      exit 0
      ;;
    -h|--help) sed -n '2,12p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
    *) die "unknown option: $arg (try --help)" ;;
  esac
done

# --- 1. Prerequisites -------------------------------------------------------
log "Checking prerequisites"
command -v node >/dev/null || die "node not found (need >= 22)"
node_major="$(node -p 'process.versions.node.split(".")[0]')"
(( node_major >= 22 )) || die "node >= 22 required, found $(node -v)"

if ! command -v pnpm >/dev/null; then
  command -v corepack >/dev/null || die "pnpm not found and corepack unavailable"
  log "Enabling pnpm via corepack"
  corepack enable
fi

# The Keycloak login theme is packaged as a JAR by Keycloakify, which needs a JDK and Maven.
command -v java >/dev/null || die "java not found (need a JDK >= 17 to build the Keycloak theme)"
command -v mvn >/dev/null || die "mvn not found (install Maven to build the Keycloak theme, e.g. sudo apt install maven)"

command -v docker >/dev/null || die "docker not found"
docker info >/dev/null 2>&1 || die "docker daemon not reachable (is it running? are you in the docker group?)"
docker compose version >/dev/null 2>&1 || die "docker compose v2 plugin not found"

# --- 2. Environment file ----------------------------------------------------
if [[ ! -f "$ENV_FILE" ]]; then
  log "Creating $ENV_FILE from .env.local.example"
  cp .env.local.example "$ENV_FILE"
fi

# Add any variable from the example that the local file lacks (never overwrites).
missing=()
while IFS= read -r line; do
  key="${line%%=*}"
  grep -qE "^[[:space:]]*${key}=" "$ENV_FILE" || missing+=("$line")
done < <(grep -E '^[A-Z_][A-Z0-9_]*=' .env.local.example)
if (( ${#missing[@]} )); then
  log "Adding missing variables to $ENV_FILE: $(printf '%s ' "${missing[@]%%=*}")"
  {
    printf '\n# Added from .env.local.example by scripts/dev.sh\n'
    printf '%s\n' "${missing[@]}"
  } >> "$ENV_FILE"
fi

if ! grep -qE '^[[:space:]]*JWT_PRIVATE_KEY=' "$ENV_FILE"; then
  log "Generating JWT_PRIVATE_KEY for apps/auth"
  {
    printf '\n# Generated by scripts/dev.sh on %s\n' "$(date -u +%Y-%m-%dT%H:%M:%SZ)"
    node apps/auth/scripts/generate-keys.mjs
  } >> "$ENV_FILE"
fi

if ! grep -qE '^[[:space:]]*INTERNAL_API_TOKEN=' "$ENV_FILE"; then
  log "Generating INTERNAL_API_TOKEN for apps/auth and apps/user"
  {
    printf '\n# Generated by scripts/dev.sh on %s\n' "$(date -u +%Y-%m-%dT%H:%M:%SZ)"
    printf 'INTERNAL_API_TOKEN=%s\n' "$(node -e "process.stdout.write(require('node:crypto').randomBytes(32).toString('hex'))")"
  } >> "$ENV_FILE"
fi

if ! grep -qE '^[[:space:]]*KC_BFF_CLIENT_SECRET=' "$ENV_FILE"; then
  log "Generating KC_BFF_CLIENT_SECRET for the Keycloak client stock-bff"
  {
    printf '\n# Generated by scripts/dev.sh on %s\n' "$(date -u +%Y-%m-%dT%H:%M:%SZ)"
    printf 'KC_BFF_CLIENT_SECRET=%s\n' "$(node -e "process.stdout.write(require('node:crypto').randomBytes(32).toString('base64url'))")"
  } >> "$ENV_FILE"
fi

# --- 3. Dependencies --------------------------------------------------------
log "Installing dependencies"
pnpm install --frozen-lockfile

# --- 4. Infrastructure ------------------------------------------------------
log "Starting Postgres, Redis and Redpanda"
"${COMPOSE[@]}" up -d --wait postgres redis kafka

# Redpanda has no compose healthcheck; wait until the broker answers.
log "Waiting for Kafka broker"
for _ in $(seq 1 60); do
  if docker exec stock-redpanda rpk cluster health 2>/dev/null | grep -qE 'Healthy:[[:space:]]+true'; then
    break
  fi
  sleep 1
done
docker exec stock-redpanda rpk cluster health 2>/dev/null | grep -qE 'Healthy:[[:space:]]+true' \
  || die "Kafka broker did not become healthy (check: docker logs stock-redpanda)"

# Keycloak keeps its own database in the same Postgres container. The volume already
# exists on most machines, so an init script would never run: create it here instead.
if ! docker exec stock-postgres psql -U stockuser -d stockdb -tAc \
    "SELECT 1 FROM pg_database WHERE datname = 'keycloak'" | grep -q 1; then
  log "Creating the keycloak database"
  docker exec stock-postgres psql -U stockuser -d stockdb -qc "CREATE DATABASE keycloak" >/dev/null
fi

# Keycloak loads the theme JAR from /opt/keycloak/providers at start-up. A changed JAR changes
# THEME_JAR_SHA, which compose passes to the container, so the container is recreated.
log "Building the Keycloak theme JAR"
pnpm build-keycloak-theme
THEME_JAR="$(ls apps/keycloak-theme/dist_keycloak/*.jar 2>/dev/null | head -n1 || true)"
[[ -n "$THEME_JAR" ]] || die "the theme build produced no JAR in apps/keycloak-theme/dist_keycloak"
export THEME_JAR_SHA
THEME_JAR_SHA="$(sha256sum "$THEME_JAR" | cut -d' ' -f1)"

# Keycloak takes 20-40 s to start; the compose healthcheck polls /health/ready on port 9000.
log "Starting Keycloak (waiting until it is ready)"
"${COMPOSE[@]}" up -d --wait --wait-timeout 180 keycloak \
  || die "Keycloak did not become ready (check: docker logs stock-keycloak)"

if $RESET_REALM; then
  [[ -f "$REALM_FILE" ]] || die "$REALM_FILE not found, nothing to reimport"
  kc_admin_user="$(grep -E '^[[:space:]]*KC_BOOTSTRAP_ADMIN_USERNAME=' "$ENV_FILE" | tail -n1 | cut -d= -f2-)"
  kc_admin_password="$(grep -E '^[[:space:]]*KC_BOOTSTRAP_ADMIN_PASSWORD=' "$ENV_FILE" | tail -n1 | cut -d= -f2-)"
  log "Deleting realm $KEYCLOAK_REALM"
  docker exec stock-keycloak /opt/keycloak/bin/kcadm.sh config credentials \
    --server http://localhost:8080 --realm master \
    --user "${kc_admin_user:-admin}" --password "${kc_admin_password:-admin}" >/dev/null \
    || die "could not log in to Keycloak as the bootstrap admin"
  # A missing realm is fine: the reimport below creates it either way.
  docker exec stock-keycloak /opt/keycloak/bin/kcadm.sh delete "realms/$KEYCLOAK_REALM" 2>/dev/null || true
  # Recreate rather than restart, so a regenerated KC_BFF_CLIENT_SECRET reaches the container.
  log "Restarting Keycloak to reimport $REALM_FILE"
  "${COMPOSE[@]}" up -d --force-recreate --wait --wait-timeout 180 keycloak \
    || die "Keycloak did not become ready after the reimport (check: docker logs stock-keycloak)"
fi

# The realm file ships the Google provider disabled (JSON cannot switch it on by condition).
# Enable it only when both credentials are in .env.local; without them it stays off and the
# login pages show no Google button. Runs on every start, so removing the credentials works too.
env_value() { grep -E "^[[:space:]]*$1=" "$ENV_FILE" | tail -n1 | cut -d= -f2-; }
google_enabled=false
if [[ -n "$(env_value GOOGLE_CLIENT_ID)" && -n "$(env_value GOOGLE_CLIENT_SECRET)" ]]; then
  google_enabled=true
fi
kc_admin_user="$(env_value KC_BOOTSTRAP_ADMIN_USERNAME)"
kc_admin_password="$(env_value KC_BOOTSTRAP_ADMIN_PASSWORD)"
docker exec stock-keycloak /opt/keycloak/bin/kcadm.sh config credentials \
  --server http://localhost:8080 --realm master \
  --user "${kc_admin_user:-admin}" --password "${kc_admin_password:-admin}" >/dev/null \
  || die "could not log in to Keycloak as the bootstrap admin"
if docker exec stock-keycloak /opt/keycloak/bin/kcadm.sh update identity-provider/instances/google \
  -r "$KEYCLOAK_REALM" -s "enabled=$google_enabled" 2>/dev/null; then
  if $google_enabled; then
    log "Google sign-in enabled"
  else
    log "Google sign-in disabled (set GOOGLE_CLIENT_ID and GOOGLE_CLIENT_SECRET in $ENV_FILE to enable it)"
  fi
else
  log "No google identity provider in the realm yet; run with --reset-realm to import it"
fi

# --- 5. Build shared packages (apps import them from dist/) -----------------
log "Building workspace"
pnpm build

if $SETUP_ONLY; then
  log "Setup complete. Run 'pnpm dev' to start the apps."
  exit 0
fi

# --- 6. Run -----------------------------------------------------------------
cat <<'EOF'

  ingestor     http://localhost:3001/health
  consumer     http://localhost:3002/health
  sse-service  http://localhost:3003/health
  user         http://localhost:3004/health
  auth         http://localhost:3005/health
  frontend     http://localhost:5173
  keycloak     http://localhost:8180/admin  (admin console; bootstrap admin from .env.local)

  Realm JSON edits need: scripts/dev.sh --reset-realm

EOF
log "Starting all apps (Ctrl+C to stop; infra keeps running, stop it with scripts/dev.sh --down)"
exec pnpm dev

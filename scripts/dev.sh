#!/usr/bin/env bash
# Bootstraps and runs the whole stack locally.
#
#   scripts/dev.sh               # setup + start every app in watch mode
#   scripts/dev.sh --setup-only  # setup, then exit (infra stays up)
#   scripts/dev.sh --down        # stop the docker infrastructure
#
# Setup is idempotent: re-running only does what is missing.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

ENV_FILE=".env.local"
COMPOSE=(docker compose --env-file "$ENV_FILE")

log()  { printf '\033[1;34m==>\033[0m %s\n' "$*"; }
die()  { printf '\033[1;31merror:\033[0m %s\n' "$*" >&2; exit 1; }

SETUP_ONLY=false
case "${1:-}" in
  "") ;;
  --setup-only) SETUP_ONLY=true ;;
  --down)
    [[ -f "$ENV_FILE" ]] || ENV_FILE=".env.local.example"
    COMPOSE=(docker compose --env-file "$ENV_FILE")
    log "Stopping infrastructure"
    "${COMPOSE[@]}" down
    exit 0
    ;;
  -h|--help) sed -n '2,8p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
  *) die "unknown option: $1 (try --help)" ;;
esac

# --- 1. Prerequisites -------------------------------------------------------
log "Checking prerequisites"
command -v node >/dev/null || die "node not found (need >= 22)"
node_major="$(node -p 'process.versions.node.split(".")[0]')"
(( node_major >= 22 )) || die "node >= 22 required, found $(node -v)"

if ! command -v pnpm >/dev/null; then
  command -v corepack >/dev/null || die "pnpm not found and corepack unavailable"
  log "Enabling pnpm via corepack"
  corepack enable
fi

command -v docker >/dev/null || die "docker not found"
docker info >/dev/null 2>&1 || die "docker daemon not reachable (is it running? are you in the docker group?)"
docker compose version >/dev/null 2>&1 || die "docker compose v2 plugin not found"

# --- 2. Environment file ----------------------------------------------------
if [[ ! -f "$ENV_FILE" ]]; then
  log "Creating $ENV_FILE from .env.local.example"
  cp .env.local.example "$ENV_FILE"
fi

# Add any variable from the example that the local file lacks (never overwrites).
missing=()
while IFS= read -r line; do
  key="${line%%=*}"
  grep -qE "^[[:space:]]*${key}=" "$ENV_FILE" || missing+=("$line")
done < <(grep -E '^[A-Z_][A-Z0-9_]*=' .env.local.example)
if (( ${#missing[@]} )); then
  log "Adding missing variables to $ENV_FILE: $(printf '%s ' "${missing[@]%%=*}")"
  {
    printf '\n# Added from .env.local.example by scripts/dev.sh\n'
    printf '%s\n' "${missing[@]}"
  } >> "$ENV_FILE"
fi

if ! grep -qE '^[[:space:]]*JWT_PRIVATE_KEY=' "$ENV_FILE"; then
  log "Generating JWT_PRIVATE_KEY for apps/auth"
  {
    printf '\n# Generated by scripts/dev.sh on %s\n' "$(date -u +%Y-%m-%dT%H:%M:%SZ)"
    node apps/auth/scripts/generate-keys.mjs
  } >> "$ENV_FILE"
fi

# --- 3. Dependencies --------------------------------------------------------
log "Installing dependencies"
pnpm install --frozen-lockfile

# --- 4. Infrastructure ------------------------------------------------------
log "Starting Postgres, Redis and Redpanda"
"${COMPOSE[@]}" up -d --wait

# Redpanda has no compose healthcheck; wait until the broker answers.
log "Waiting for Kafka broker"
for _ in $(seq 1 60); do
  if docker exec stock-redpanda rpk cluster health 2>/dev/null | grep -qE 'Healthy:[[:space:]]+true'; then
    break
  fi
  sleep 1
done
docker exec stock-redpanda rpk cluster health 2>/dev/null | grep -qE 'Healthy:[[:space:]]+true' \
  || die "Kafka broker did not become healthy (check: docker logs stock-redpanda)"

# --- 5. Build shared packages (apps import them from dist/) -----------------
log "Building workspace"
pnpm build

if $SETUP_ONLY; then
  log "Setup complete. Run 'pnpm dev' to start the apps."
  exit 0
fi

# --- 6. Run -----------------------------------------------------------------
cat <<'EOF'

  ingestor     http://localhost:3001/health
  consumer     http://localhost:3002/health
  sse-service  http://localhost:3003/health
  user         http://localhost:3004/health
  auth         http://localhost:3005/health
  frontend     http://localhost:5173

EOF
log "Starting all apps (Ctrl+C to stop; infra keeps running, stop it with scripts/dev.sh --down)"
exec pnpm dev
